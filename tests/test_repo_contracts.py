"""Contract tests for the README and GitHub Actions workflow.

These tests catch the class of mistakes that made the original automation fail:
missing section markers, unpinned actions, unsafe triggers, and malformed YAML.
"""

from __future__ import annotations

import json
import re
import sys
import unittest
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

import update_profile as up  # noqa: E402

WORKFLOW_PATH = ROOT / ".github" / "workflows" / "update-profile.yml"
README_PATH = ROOT / "README.md"
SUMMARIES_PATH = ROOT / "scripts" / "project_summaries.json"


class ReadmeContractTests(unittest.TestCase):
    def setUp(self) -> None:
        self.readme = README_PATH.read_text(encoding="utf-8")

    def test_readme_exists_and_is_not_empty(self) -> None:
        self.assertGreater(len(self.readme.strip()), 500)

    def test_every_generated_section_has_exactly_one_marker_pair(self) -> None:
        for name in up.SECTION_NAMES:
            self.assertEqual(
                self.readme.count(f"<!-- {name}:start -->"),
                1,
                f"{name} start marker is missing or duplicated",
            )
            self.assertEqual(
                self.readme.count(f"<!-- {name}:end -->"),
                1,
                f"{name} end marker is missing or duplicated",
            )

    def test_section_names_in_readme_match_the_updater(self) -> None:
        found = set(re.findall(r"<!-- ([a-z-]+):start -->", self.readme))
        self.assertEqual(found, set(up.SECTION_NAMES))

    def test_manual_portfolio_sections_survive(self) -> None:
        for heading in (
            "## Operating principles",
            "## Engineering focus",
            "## Technical range",
            "## Selected engineering work",
            "## Current focus",
            "## Contact",
        ):
            self.assertIn(heading, self.readme)

    def test_no_generator_placeholder_remains(self) -> None:
        self.assertNotIn("_Generated by the profile updater._", self.readme)

    def test_no_fake_traction_claims(self) -> None:
        lowered = self.readme.lower()
        for claim in ("10k+", "100+ stars", "thousands of users", "used by"):
            self.assertNotIn(claim, lowered)


class WorkflowContractTests(unittest.TestCase):
    def setUp(self) -> None:
        self.text = WORKFLOW_PATH.read_text(encoding="utf-8")
        self.data = yaml.safe_load(self.text)

    def triggers(self) -> dict[str, object]:
        return self.data.get("on") or self.data.get(True) or {}

    def test_yaml_is_valid(self) -> None:
        self.assertIsInstance(self.data, dict)
        self.assertIn("jobs", self.data)

    def test_has_schedule_and_manual_dispatch(self) -> None:
        triggers = self.triggers()
        self.assertIn("schedule", triggers)
        self.assertIn("workflow_dispatch", triggers)
        self.assertEqual(triggers["schedule"][0]["cron"], "23 6 * * *")

    def test_permissions_are_minimal(self) -> None:
        self.assertEqual(self.data.get("permissions"), {"contents": "write"})

    def test_push_trigger_cannot_loop_on_generated_files(self) -> None:
        push = self.triggers().get("push") or {}
        paths = push.get("paths") or []
        self.assertNotIn("README.md", paths)
        self.assertFalse(any(path.startswith("assets/") for path in paths))

    def test_every_uses_is_pinned_to_a_full_commit_sha(self) -> None:
        uses = re.findall(r"^\s*uses:\s*(\S+)", self.text, flags=re.MULTILINE)
        self.assertTrue(uses)
        for action in uses:
            self.assertRegex(
                action,
                r"^[^@]+@[0-9a-f]{40}$",
                f"unpinned action: {action}",
            )

    def test_job_has_timeout_and_concurrency(self) -> None:
        job = self.data["jobs"]["update-profile"]
        self.assertEqual(job.get("timeout-minutes"), 10)
        self.assertIn("concurrency", self.data)

    def test_tests_run_before_generation(self) -> None:
        steps = self.data["jobs"]["update-profile"]["steps"]
        run_text = "\n".join(str(step.get("run", "")) for step in steps)
        self.assertIn("compileall", run_text)
        self.assertIn("unittest discover", run_text)
        names = [step.get("name", "") for step in steps]
        self.assertLess(
            names.index("Compile and test"), names.index("Refresh generated README sections")
        )

    def test_token_is_scoped_to_the_run_step(self) -> None:
        steps = self.data["jobs"]["update-profile"]["steps"]
        run_steps = [step for step in steps if step.get("name") in {"Refresh generated README sections", "Commit generated changes"}]
        self.assertEqual(len(run_steps), 2)
        for step in run_steps:
            self.assertEqual(
                step.get("env", {}).get("GITHUB_TOKEN"), "${{ secrets.GITHUB_TOKEN }}"
            )

    def test_commit_step_only_stages_generated_files(self) -> None:
        self.assertIn("git add README.md", self.text)
        self.assertIn("assets/commit-activity.svg", self.text)
        self.assertIn("git diff --cached --quiet", self.text)
        self.assertIn("[skip ci]", self.text)

    def test_no_pull_request_target(self) -> None:
        self.assertNotIn("pull_request_target", self.text)


class SummariesContractTests(unittest.TestCase):
    def test_summaries_are_valid_json_strings(self) -> None:
        data = json.loads(SUMMARIES_PATH.read_text(encoding="utf-8"))
        self.assertIsInstance(data, dict)
        self.assertTrue(data)
        for key, value in data.items():
            self.assertIsInstance(key, str)
            self.assertIsInstance(value, str)
            self.assertTrue(value.strip())

    def test_summaries_avoid_unverified_traction_claims(self) -> None:
        lowered = SUMMARIES_PATH.read_text(encoding="utf-8").lower()
        for claim in ("10x", "thousands", "guaranteed", "best-in-class"):
            self.assertNotIn(claim, lowered)


class SecretScanTests(unittest.TestCase):
    PATTERNS = (
        re.compile(r"ghp_[A-Za-z0-9]{30,}"),
        re.compile(r"github_pat_[A-Za-z0-9_]{20,}"),
        re.compile(r"AKIA[0-9A-Z]{16}"),
        re.compile(r"BEGIN (RSA|OPENSSH|EC) PRIVATE KEY"),
    )

    def test_no_obvious_secret_material(self) -> None:
        for path in ROOT.rglob("*"):
            if not path.is_file() or ".git" in path.parts:
                continue
            try:
                text = path.read_text(encoding="utf-8")
            except (UnicodeDecodeError, OSError):
                continue
            for pattern in self.PATTERNS:
                self.assertIsNone(pattern.search(text), f"possible secret in {path}")


if __name__ == "__main__":
    unittest.main()
